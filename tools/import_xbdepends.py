"""Regenerates src/analysis/xbdepends_data.hpp from the xbdepends sample (MIT)
in microsoft/Xbox-GDK-Samples. Files are fetched at a pinned commit and hash checked.

usage: import_xbdepends.py OUTPUT [DIR_WITH_LOCAL_COPIES]
"""
import hashlib
import re
import sys
import urllib.request
from pathlib import Path

COMMIT = "b1e77b6ac10f95b07296025fda171ca2ddc42dbe"
BASE = f"https://raw.githubusercontent.com/microsoft/Xbox-GDK-Samples/{COMMIT}/Samples/Tools/xbdepends/"
FILES = {
    "KnownDLLs.h": "3fad8318aa7329810eafc2d1248db9a868f4f678433be91ac1bb375d4ccbfb0c",
    "GameOSAPIs.h": "c402a683cc7f00005295bf59999af613096960b3ef92c733c6f2912ca4b930ba",
    "xbdepends.cpp": "06a44b6c1b466fab363f7a0074437fb0e0f18bb166a9f9a0b48e9e8858b53f0d",
}
# upstream array -> (our name, lowercase?)
TABLES = {
    "c_CoreOS": ("core_os", True), "c_Win32": ("win32_legacy", True),
    "c_GameOSOnly": ("game_os_only", True), "c_SystemOS": ("system_os", True),
    "c_PCOnly": ("pc_only", True), "c_PCVendor": ("pc_vendor", True),
    "c_LegacyERA": ("legacy_era", True), "c_LegacyDXSDK": ("legacy_dxsdk", True),
    "c_LegacyDXSDKDebug": ("legacy_dxsdk_debug", True), "c_GDK": ("gdk", True),
    "c_DevOnlyGDK": ("dev_only_gdk", True), "c_Direct3D_Legacy": ("d3d_legacy", True),
    "c_Direct3D_Stock": ("d3d_stock", True), "c_Direct3D_XboxOne": ("d3d_xbox_one", True),
    "c_Direct3D_Scarlett": ("d3d_scarlett", True),
    "c_GameOSAPIs": ("game_os_apis", False), "c_additionalGameOSAPIs": ("additional_game_os_apis", False),
}


def fetch(name, directory):
    local = directory / name if directory else None
    data = local.read_bytes() if local else urllib.request.urlopen(BASE + name).read()
    if hashlib.sha256(data).hexdigest() != FILES[name]:
        raise SystemExit(f"{name}: SHA-256 mismatch against pinned upstream revision")
    return data.decode("utf-8-sig")


def main():
    out = Path(sys.argv[1])
    directory = Path(sys.argv[2]) if len(sys.argv) > 2 else None
    text = "\n".join(fetch(name, directory) for name in FILES)
    lines = [
        "// Generated by tools/import_xbdepends.py; do not edit.",
        "// Source: microsoft/Xbox-GDK-Samples, Samples/Tools/xbdepends at commit",
        f"// {COMMIT} (MIT License,",
        "// Copyright (c) Microsoft Corporation; see THIRD-PARTY.md).",
        "// clang-format off",
        "#pragma once",
        "#include <array>",
        "#include <string_view>",
        "",
        "namespace xs::analysis::data {",
    ]
    for upstream, (name, lower) in TABLES.items():
        body = re.search(r"const char\* " + upstream + r"\[\] =\s*\{(.*?)\};", text, re.S)
        if not body:
            raise SystemExit(f"table {upstream} not found")
        values = re.findall(r'"([^"]+)"', re.sub(r"//[^\n]*", "", body.group(1)))
        values = sorted({v.lower() if lower else v for v in values})
        lines.append(f"inline constexpr std::array<std::string_view, {len(values)}> {name}{{")
        lines += [f'    "{v}",' for v in values]
        lines.append("};")
    lines.append("} // namespace xs::analysis::data")
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
